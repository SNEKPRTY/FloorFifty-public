/**
 * `pnpm assets:palette` emits the CSS half of the palette here.
 *
 * The Svelte layer must not restate a colour. Every token below is the same
 * swatch the renderer resolves, so a DOM panel and a drawn HUD chip cannot
 * drift apart.
 */

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { PLAYER_COLORS, ROLES, playerColorHex, roleHex, type RoleName } from "../src/roles";

const OUT = resolve(import.meta.dirname, "..", "src", "palette.css");

export function emitPaletteCss(): string {
  const roles = (Object.keys(ROLES) as RoleName[])
    .map(
      (role) => `  --ff-${role.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}: ${roleHex(role)};`,
    )
    .join("\n");
  const players = Object.keys(PLAYER_COLORS)
    .map((name) => `  --ff-player-${name}: ${playerColorHex(name as never)};`)
    .join("\n");

  return `/* GENERATED by tools/generate-roles.ts. Do not edit.
   Run \`pnpm assets:palette\`. Palette: Resurrect 64 by Kerrie Lake. */
:root {
${roles}
${players}
}
`;
}

export function writePaletteCss(): void {
  writeFileSync(OUT, emitPaletteCss());
}
