/**
 * `pnpm assets:palette`.
 *
 * The palette has one authored form -- the canonical hex file -- and three
 * derived ones: the TypeScript swatches the tools and renderer import, the CSS
 * custom properties the Svelte layer reads, and the lookup texture the
 * palette-lock shader samples. Deriving all three from one file is what keeps a
 * drawn platform and a DOM button resolving the same colour.
 *
 * `palette.css` is emitted by `generate-roles.ts` in Task 2, because it needs
 * the role bindings this file knows nothing about.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { PNG } from "pngjs";
import { writePaletteCss } from "./generate-roles";

const PACKAGE_ROOT = resolve(import.meta.dirname, "..");
const SOURCE = resolve(PACKAGE_ROOT, "palettes", "resurrect64.hex");
const SWATCHES_OUT = resolve(PACKAGE_ROOT, "src", "swatches.ts");
const LUT_OUT = resolve(PACKAGE_ROOT, "assets", "palette-lut.png");

export function readCanonicalSwatches(path = SOURCE): string[] {
  const swatches = readFileSync(path, "utf8")
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith("#"))
    .map((line) => `#${line.toLowerCase()}`);

  if (swatches.length !== 64) {
    throw new Error(`expected 64 swatches in ${path}, found ${swatches.length}`);
  }
  for (const swatch of swatches) {
    if (!/^#[0-9a-f]{6}$/.test(swatch)) throw new Error(`not a hex swatch: ${swatch}`);
  }
  if (new Set(swatches).size !== swatches.length) {
    throw new Error("the palette contains a duplicate swatch");
  }
  return swatches;
}

function emitSwatches(swatches: string[]): string {
  const entries = swatches.map((swatch) => `  "${swatch}",`).join("\n");
  return `/**
 * The Resurrect 64 palette.
 *
 * GENERATED by tools/generate-palette.ts from palettes/resurrect64.hex.
 * Do not edit. Run \`pnpm assets:palette\` instead.
 *
 * Palette by Kerrie Lake. https://lospec.com/palette-list/resurrect-64
 */

export const RESURRECT64 = [
${entries}
] as const;

export type SwatchIndex = number;

/** Channel triple for a swatch index, for callers that draw rather than style. */
export function swatchRgb(index: SwatchIndex): readonly [number, number, number] {
  const swatch = RESURRECT64[index];
  if (swatch === undefined) throw new Error(\`no swatch at index \${index}\`);
  return [
    Number.parseInt(swatch.slice(1, 3), 16),
    Number.parseInt(swatch.slice(3, 5), 16),
    Number.parseInt(swatch.slice(5, 7), 16),
  ];
}

/**
 * The palette entry closest to a colour.
 *
 * Distance is weighted toward green, which the eye resolves most finely, so a
 * quantized sprite keeps its form rather than its arithmetic.
 */
export function nearestSwatch(r: number, g: number, b: number): SwatchIndex {
  let best = 0;
  let bestDistance = Number.POSITIVE_INFINITY;
  for (let index = 0; index < RESURRECT64.length; index += 1) {
    const [sr, sg, sb] = swatchRgb(index);
    const distance = 2 * (r - sr) ** 2 + 4 * (g - sg) ** 2 + 3 * (b - sb) ** 2;
    if (distance >= bestDistance) continue;
    bestDistance = distance;
    best = index;
  }
  return best;
}
`;
}

function emitLut(swatches: string[]): Buffer {
  const png = new PNG({ width: 64, height: 1 });
  swatches.forEach((swatch, index) => {
    const at = index * 4;
    png.data[at] = Number.parseInt(swatch.slice(1, 3), 16);
    png.data[at + 1] = Number.parseInt(swatch.slice(3, 5), 16);
    png.data[at + 2] = Number.parseInt(swatch.slice(5, 7), 16);
    png.data[at + 3] = 255;
  });
  return PNG.sync.write(png);
}

function main(): void {
  const swatches = readCanonicalSwatches();
  writeFileSync(SWATCHES_OUT, emitSwatches(swatches));
  writeFileSync(LUT_OUT, emitLut(swatches));
  writePaletteCss();
  process.stdout.write(
    `palette: 64 swatches -> src/swatches.ts, src/palette.css, assets/palette-lut.png\n`,
  );
}

main();
